/* The engine re-renders #panel and #tabs on every tab or month change. Watch both and repaint ours. */
let hooked = false;
const watcher = new MutationObserver(() => {
  const panel = $('#panel'), tabs = $('#tabs');
  if (panel && tabs && !hooked){
    hooked = true; watcher.disconnect();
    /* Only react when the ENGINE changed the panel; our own panel and Updates view are ignored,
       otherwise appending the pins list would retrigger this forever. */
    const ours = n => n.nodeType === 1 && (n.classList.contains('cb-panel') || n.hasAttribute('data-cb-own'));
    new MutationObserver(muts => {
      const engine = muts.some(m => [...m.addedNodes].some(n => !ours(n)));
      if (!engine) return;
      if (OPEN && !panel.querySelector('[data-cb-own]')) OPEN = false;
      clearTimeout(window._cbP); window._cbP = setTimeout(paint, 60);
    }).observe(panel, { childList: true });
    new MutationObserver(muts => {
      if (muts.some(m => [...m.addedNodes].some(n => n.nodeType === 1 && !n.dataset.collab))) ensureTab();
    }).observe(tabs, { childList: true });
    chrome(); loadPins();
    if ((location.hash || '') === '#updates') setTimeout(() => { if (FB_OK) openUpdates(); }, 400);
  }
});
